/*
 * Generate resource/engwords.dic, the english words for hangul_eng_typo()
 * and hangul_han_typo(): the sorted lower case words, one per line.
 *
 *   gen_engwords [-x engwords-extra.txt] words.txt [notice.txt] > ../resource/engwords.dic
 *
 * words.txt is a word list like as /usr/share/dict/american-english (SCOWL).
 * engwords-extra.txt has the commands and terms not in it, like as "git".
 * notice.txt is the copyright notice of the word list for the header.
 */

#define _CRT_SECURE_NO_WARNINGS
#include <windows.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <io.h>
#include <fcntl.h>
#include "hangul.h"

#define MAXWORDS 100000

static char *words[MAXWORDS];

static int CompareWord(const void *a, const void *b)
{
    return strcmp(*(char **)a, *(char **)b);
}

// the words of the letters only, in the lower case
static int ReadWords(FILE *fp, int n)
{
    char line[256];
    int i, len;

    while (fgets(line, sizeof(line), fp) != NULL && n < MAXWORDS)
    {
        line[strcspn(line, "\r\n")] = '\0';
        len = (int)strlen(line);
        if (len == 0 || len > ENGTYPO_MAXLEN)
            continue;
        for (i = 0; i < len; i++)
        {
            if (line[i] >= 'A' && line[i] <= 'Z')
                line[i] += 'a' - 'A';
            else if (line[i] < 'a' || line[i] > 'z')
                break;
        }
        if (i < len)
            continue;
        words[n++] = _strdup(line);
    }
    return n;
}

int main(int argc, char **argv)
{
    char line[256];
    const char *pszExtra = NULL;
    FILE *fp;
    int i, len, n = 0;

    if (argc > 2 && strcmp(argv[1], "-x") == 0)
    {
        pszExtra = argv[2];
        argc -= 2;
        argv += 2;
    }
    if (argc < 2 || (fp = fopen(argv[1], "r")) == NULL)
    {
        fprintf(stderr, "usage: gen_engwords [-x engwords-extra.txt] words.txt [notice.txt]\n");
        return 1;
    }
    n = ReadWords(fp, n);
    fclose(fp);
    if (pszExtra != NULL)
    {
        if ((fp = fopen(pszExtra, "r")) == NULL)
        {
            fprintf(stderr, "gen_engwords: %s not found\n", pszExtra);
            return 1;
        }
        n = ReadWords(fp, n);
        fclose(fp);
    }

    qsort(words, n, sizeof(words[0]), CompareWord);

    // LF like as the other sources
    _setmode(_fileno(stdout), _O_BINARY);
    printf("# English words for the auto Han/Eng correction.\n");
    printf("# Generated by tests/gen_engwords.c from %s%s. Do not edit.\n",
           strrchr(argv[1], '\\') ? strrchr(argv[1], '\\') + 1 : argv[1],
           pszExtra != NULL ? " and engwords-extra.txt" : "");
    if (argc > 2 && (fp = fopen(argv[2], "r")) != NULL)
    {
        printf("#\n");
        while (fgets(line, sizeof(line), fp) != NULL)
        {
            line[strcspn(line, "\r\n")] = '\0';
            for (len = (int)strlen(line); len > 0 && (line[len - 1] == ' ' || line[len - 1] == '\t'); len--)
                line[len - 1] = '\0';
            if (line[0])
                printf("# %s\n", line);
            else
                printf("#\n");
        }
        fclose(fp);
    }

    // one word per line
    for (i = 0, len = 0; i < n; i++)
    {
        if (i > 0 && strcmp(words[i - 1], words[i]) == 0)
            continue;
        printf("%s\n", words[i]);
        len++;
    }
    fprintf(stderr, "%d words\n", len);
    return 0;
}
