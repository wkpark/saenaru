/*
 * Generate resource/engwords.dic, the english words for hangul_eng_typo()
 * and hangul_han_typo(): the sorted lower case words, one per line.
 *
 *   gen_engwords -o ../resource/engwords.dic [-x engwords-extra.txt] words.txt [notice.txt]
 *
 * Without -o, it is written to stdout, but the redirection of PowerShell 5
 * writes UTF-16, which hangul_is_eng_word() can not read.
 * words.txt is a word list like as /usr/share/dict/american-english (SCOWL).
 * engwords-extra.txt has the commands and terms not in it, like as "git".
 * notice.txt is the copyright notice of the word list for the header.
 */

#define _CRT_SECURE_NO_WARNINGS
#include <windows.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <io.h>
#include <fcntl.h>
#include "hangul.h"

#define MAXWORDS 100000

static char *words[MAXWORDS];

static int CompareWord(const void *a, const void *b)
{
    return strcmp(*(char **)a, *(char **)b);
}

// the words of the letters only, in the lower case
static int ReadWords(FILE *fp, int n)
{
    char line[256];
    int i, len;

    while (fgets(line, sizeof(line), fp) != NULL)
    {
        if (strchr(line, '\n') == NULL && !feof(fp))
        {
            // a line longer than the buffer is not a word
            while (fgets(line, sizeof(line), fp) != NULL && strchr(line, '\n') == NULL)
                ;
            continue;
        }
        line[strcspn(line, "\r\n")] = '\0';
        len = (int)strlen(line);
        if (len == 0 || len > ENGTYPO_MAXLEN)
            continue;
        for (i = 0; i < len; i++)
        {
            if (line[i] >= 'A' && line[i] <= 'Z')
                line[i] += 'a' - 'A';
            else if (line[i] < 'a' || line[i] > 'z')
                break;
        }
        if (i < len)
            continue;
        if (n >= MAXWORDS)
        {
            fprintf(stderr, "gen_engwords: more than %d words\n", MAXWORDS);
            exit(1);
        }
        words[n++] = _strdup(line);
    }
    return n;
}

int main(int argc, char **argv)
{
    char line[256];
    const char *pszExtra = NULL, *pszOut = NULL, *pszName;
    FILE *fp, *out = stdout;
    int i, len, n = 0;

    while (argc > 2 && (strcmp(argv[1], "-x") == 0 || strcmp(argv[1], "-o") == 0))
    {
        if (argv[1][1] == 'x')
            pszExtra = argv[2];
        else
            pszOut = argv[2];
        argc -= 2;
        argv += 2;
    }
    if (argc < 2 || (fp = fopen(argv[1], "r")) == NULL)
    {
        fprintf(stderr, "usage: gen_engwords [-o engwords.dic] [-x engwords-extra.txt] words.txt [notice.txt]\n");
        return 1;
    }
    n = ReadWords(fp, n);
    fclose(fp);
    if (pszExtra != NULL)
    {
        if ((fp = fopen(pszExtra, "r")) == NULL)
        {
            fprintf(stderr, "gen_engwords: %s not found\n", pszExtra);
            return 1;
        }
        n = ReadWords(fp, n);
        fclose(fp);
    }

    qsort(words, n, sizeof(words[0]), CompareWord);

    // LF like as the other sources
    if (pszOut != NULL && (out = fopen(pszOut, "wb")) == NULL)
    {
        fprintf(stderr, "gen_engwords: can not write %s\n", pszOut);
        return 1;
    }
    if (out == stdout)
        _setmode(_fileno(stdout), _O_BINARY);
    // the file name only, of the path by '\\' or '/'
    for (pszName = argv[1] + strlen(argv[1]); pszName > argv[1] && pszName[-1] != '\\' && pszName[-1] != '/'; pszName--)
        ;
    fprintf(out, "# English words for the auto Han/Eng correction.\n");
    fprintf(out, "# Generated by tests/gen_engwords.c from %s%s. Do not edit.\n",
           pszName, pszExtra != NULL ? " and engwords-extra.txt" : "");
    if (argc > 2 && (fp = fopen(argv[2], "r")) != NULL)
    {
        fprintf(out, "#\n");
        while (fgets(line, sizeof(line), fp) != NULL)
        {
            line[strcspn(line, "\r\n")] = '\0';
            for (len = (int)strlen(line); len > 0 && (line[len - 1] == ' ' || line[len - 1] == '\t'); len--)
                line[len - 1] = '\0';
            if (line[0])
                fprintf(out, "# %s\n", line);
            else
                fprintf(out, "#\n");
        }
        fclose(fp);
    }

    // one word per line
    for (i = 0, len = 0; i < n; i++)
    {
        if (i > 0 && strcmp(words[i - 1], words[i]) == 0)
            continue;
        fprintf(out, "%s\n", words[i]);
        len++;
    }
    if (out != stdout && fclose(out) != 0)
    {
        fprintf(stderr, "gen_engwords: can not write %s\n", pszOut);
        return 1;
    }
    fprintf(stderr, "%d words\n", len);
    return 0;
}
