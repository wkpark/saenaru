/*
 * Generate src/engwords.h, the english words typed into hangul syllables
 * on the 2-set keyboard. They are not converted by hangul_eng_typo().
 *
 *   gen_engwords words.txt [notice.txt] > ../src/engwords.h
 *
 * words.txt is a word list like as /usr/share/dict/american-english (SCOWL).
 * notice.txt is the copyright notice of the word list for the header.
 */

#define _CRT_SECURE_NO_WARNINGS
#include <windows.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <io.h>
#include <fcntl.h>
#include "hangul.h"

#define MAXWORDS 100000

static char *words[MAXWORDS];

static int CompareWord(const void *a, const void *b)
{
    return strcmp(*(char **)a, *(char **)b);
}

static BOOL IsSyllables(const char *word, BOOL fCapital)
{
    WCHAR eng[ENGTYPO_MAXLEN + 1], han[ENGTYPO_MAXLEN + 1];
    int i;

    for (i = 0; word[i] != '\0'; i++)
        eng[i] = (WCHAR)word[i];
    eng[i] = L'\0';
    if (fCapital)
        eng[0] -= 'a' - 'A';
    return hangul_eng_to_syllables(eng, han, ARRAYSIZE(han)) > 0;
}

int main(int argc, char **argv)
{
    char line[256];
    FILE *fp;
    int i, len, n = 0;

    if (argc < 2 || (fp = fopen(argv[1], "r")) == NULL)
    {
        fprintf(stderr, "usage: gen_engwords words.txt [notice.txt]\n");
        return 1;
    }
    set_keyboard(LAYOUT_OLD2BUL);

    while (fgets(line, sizeof(line), fp) != NULL && n < MAXWORDS)
    {
        line[strcspn(line, "\r\n")] = '\0';
        len = (int)strlen(line);
        if (len == 0 || len > ENGTYPO_MAXLEN)
            continue;
        // letters only, in the lower case
        for (i = 0; i < len; i++)
        {
            if (line[i] >= 'A' && line[i] <= 'Z')
                line[i] += 'a' - 'A';
            else if (line[i] < 'a' || line[i] > 'z')
                break;
        }
        if (i < len)
            continue;
        if (IsSyllables(line, FALSE) || IsSyllables(line, TRUE))
            words[n++] = _strdup(line);
    }
    fclose(fp);

    qsort(words, n, sizeof(words[0]), CompareWord);

    // LF like as the other sources
    _setmode(_fileno(stdout), _O_BINARY);
    printf("/*\n * English words typed into hangul syllables on the 2-set keyboard.\n");
    printf(" * Generated by tests/gen_engwords.c from %s. Do not edit.\n",
           strrchr(argv[1], '\\') ? strrchr(argv[1], '\\') + 1 : argv[1]);
    if (argc > 2 && (fp = fopen(argv[2], "r")) != NULL)
    {
        printf(" *\n");
        while (fgets(line, sizeof(line), fp) != NULL)
        {
            line[strcspn(line, "\r\n")] = '\0';
            for (len = (int)strlen(line); len > 0 && (line[len - 1] == ' ' || line[len - 1] == '\t'); len--)
                line[len - 1] = '\0';
            printf(line[0] ? " * %s\n" : " *\n", line);
        }
        fclose(fp);
    }
    printf(" */\n\nstatic const char *eng_words[] = {\n");
    for (i = 0, len = 0; i < n; i++)
    {
        if (i > 0 && strcmp(words[i - 1], words[i]) == 0)
            continue;
        printf("%s\"%s\",", (len % 8) ? " " : "    ", words[i]);
        if (++len % 8 == 0)
            printf("\n");
    }
    printf("%s};\n", (len % 8) ? "\n" : "");
    fprintf(stderr, "%d words\n", len);
    return 0;
}
